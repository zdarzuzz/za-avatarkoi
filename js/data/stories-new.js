// Истории по кадрам из папки «манга» (Яндекс Диск, 26.10.2026).
// Порядок кадров восстановлен по сюжету: имена исходных файлов случайные.
// Раскладка: каждый ряд — номера кадров; пропорции берутся из FRAMES, кадры не обрезаются.
// Одиночный вертикальный или квадратный кадр — «деталь»: он уже основной ширины.

import { FRAMES } from './frames.js';

const M = 'assets/images/manga/';
const b = (text, x, y, w, tail = 'bl', you = false) => ({ text, x, y, w, tail, you });
const you = (text, x, y, w, tail = 'br') => b(text, x, y, w, tail, true);

/** Собрать ряды кадров из номеров и описаний. */
function build(sit, ch, layout, panels) {
  const dims = FRAMES[`${sit}/${ch}`];
  return layout.map((nums) => {
    const H = 1000;
    const row = {
      h: H,
      panels: nums.map((n) => {
        const [w, h, sw, sh] = dims[n - 1];
        return {
          w: Math.round((H * w) / h),
          img: `${M}${sit}/${ch}-${n}.webp`,
          imgSm: `${M}${sit}/${ch}-${n}-sm.webp`,
          imgW: w, imgH: h, smW: sw, smH: sh,
          ...panels[n - 1],
        };
      }),
    };
    if (nums.length === 1 && dims[nums[0] - 1][0] / dims[nums[0] - 1][1] < 1.2) row.detail = true;
    return row;
  });
}

const story = (situationId, characterId, layout, panels, rest) => ({
  situationId, characterId, rows: build(situationId, characterId, layout, panels), ...rest,
});

