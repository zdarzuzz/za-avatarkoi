// 18 историй: 6 персонажей × 3 ситуации. Сюжет определяется парой situationId + characterId.
//
// Структура истории:
//   rows     — ряды кадров. h — высота ряда в макетных пикселях при ширине колонки 797 px,
//              w у кадра — его доля ширины ряда (тоже в макетных пикселях).
//   panel    — img (путь к кадру), ready (кадр есть в проекте), fit (кадрирование из Figma),
//              scene (описание сцены для иллюстратора / генерации), bubbles (реплики HTML-текстом).
//   bubble   — x, y, w в % от кадра; tail — угол «хвостика» (bl, br, tl, tr); you — реплика читателя.
//   closing  — подпись после манги.
//   comments — три наблюдения авторского комментария, опираются на поступки в этой истории.
//   hints    — спокойные подсказки после ответа «Да», «Нет», «Не знаю».
//
// Истории Сони и Алины в поездке перенесены из Figma (MacBook Air 13 и 15) с исходными кадрами.

import { MANGA_READY } from './manga-manifest.js';

const M = 'assets/images/manga/';

const b = (text, x, y, w, tail = 'bl', you = false) => ({ text, x, y, w, tail, you });
const you = (text, x, y, w, tail = 'br') => b(text, x, y, w, tail, true);

// Шаблон из шести кадров: широкий / два узких / широкий / два узких.
// Кадр ждёт файл assets/images/manga/<situation>/<character>-<n>.webp.
// Когда файл добавлен, впиши его путь в js/data/manga-manifest.js (см. README).
function withImages(sit, char, panels) {
  const img = (i) => `${M}${sit}/${char}-${i + 1}.webp`;
  const p = panels.map((panel, i) => ({ img: img(i), ready: MANGA_READY.includes(img(i)), ...panel }));
  return [
    { h: 363, panels: [{ w: 797, ...p[0] }] },
    { h: 343, panels: [{ w: 392, ...p[1] }, { w: 393, ...p[2] }] },
    { h: 400, panels: [{ w: 797, ...p[3] }] },
    { h: 343, panels: [{ w: 392, ...p[4] }, { w: 393, ...p[5] }] },
  ];
}

