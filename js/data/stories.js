export const getStory = (situationId, characterId) =>
  STORIES.find((s) => s.situationId === situationId && s.characterId === characterId);

export const storiesIn = (situationId) => STORIES.filter((s) => s.situationId === situationId);

/** Ситуации, в которых можно показать обязательные две истории. */
export const availableSituations = (allIds) =>
  allIds.filter((id) => storiesIn(id).length >= 2);
